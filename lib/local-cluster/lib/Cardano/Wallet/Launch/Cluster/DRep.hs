-- | Generate a DRep key pair in the cluster directory and return the hash of
-- its verification key, which names the DRep in 'registerDRep' and
-- 'retireDRep'.
genDRepKeys :: ClusterM DRepKeyHash
genDRepKeys = do
    Config{..} <- ask
    let era = clusterEraToString cfgLastHardFork
        drepsDir = absDirOf cfgClusterDir </> relDir "dreps"
    liftIO $ createDirectoryIfMissing True (toFilePath drepsDir)
    keysDir <-
        fmap absDir
            $ liftIO
            $ createTempDirectory (toFilePath drepsDir) "keys"
    cli
        [ era
        , "governance"
        , "drep"
        , "key-gen"
        , "--verification-key-file"
        , toFilePath $ keysDir </> verificationKeyFile
        , "--signing-key-file"
        , toFilePath $ keysDir </> signingKeyFile
        ]
    hex <-
        cliLine
            [ era
            , "governance"
            , "drep"
            , "id"
            , "--drep-verification-key-file"
            , toFilePath $ keysDir </> verificationKeyFile
            , "--output-hex"
            ]
    drep <-
        either
            (\e -> liftIO $ throwIO $ userError $ "DRep id: " <> e)
            (pure . DRepKeyHash)
            $ convertFromBase Base16 (B8.pack hex)
    drepDir <- askDRepDir drep
    liftIO $ renameDirectory (toFilePath keysDir) (toFilePath drepDir)
    pure drep

-- | Register a DRep generated by 'genDRepKeys', paying the deposit that the
-- protocol parameters require, and return once the ledger holds the DRep as
-- registered. A DRep that the ledger already holds as registered is left as
-- it is. A DRep retired with 'retireDRep' is registered again with the same
-- keys.
registerDRep :: CardanoNodeConn -> DRepKeyHash -> ClusterM ()
registerDRep conn drep = do
    registered <- isJust <$> queryDRepDeposit conn drep
    unless registered $ do
        Config{..} <- ask
        drepDir <- askDRepDir drep
        params <- cliQuery conn ["query", "protocol-parameters"]
        deposit <-
            maybe (unexpected "protocol parameters" params) pure
                $ params ^? key "dRepDeposit" . _Integer
        let cert = drepDir </> relFile "registration.cert"
        cli
            [ clusterEraToString cfgLastHardFork
            , "governance"
            , "drep"
            , "registration-certificate"
            , "--drep-key-hash"
            , drepKeyHashHex drep
            , "--key-reg-deposit-amt"
            , show deposit
            , "--out-file"
            , toFilePath cert
            ]
        traceClusterLog
            $ MsgDebug
            $ "Registering DRep " <> T.pack (drepKeyHashHex drep)
        submitDRepCertificate
            conn
            drep
            (FileOf cert)
            (faucetAmt - deposit)
            "registration"
        waitForDRep conn drep True

-- | Retire a DRep generated by 'genDRepKeys', which refunds its deposit, and
-- return once the ledger no longer holds the DRep. A DRep that the ledger
-- does not hold is left as it is.
retireDRep :: CardanoNodeConn -> DRepKeyHash -> ClusterM ()
retireDRep conn drep = do
    registration <- queryDRepDeposit conn drep
    forM_ registration $ \deposit -> do
        Config{..} <- ask
        drepDir <- askDRepDir drep
        let cert = drepDir </> relFile "retirement.cert"
        cli
            [ clusterEraToString cfgLastHardFork
            , "governance"
            , "drep"
            , "retirement-certificate"
            , "--drep-key-hash"
            , drepKeyHashHex drep
            , "--deposit-amt"
            , show deposit
            , "--out-file"
            , toFilePath cert
            ]
        traceClusterLog
            $ MsgDebug
            $ "Retiring DRep " <> T.pack (drepKeyHashHex drep)
        submitDRepCertificate
            conn
            drep
            (FileOf cert)
            (faucetAmt + deposit)
            "retirement"
        waitForDRep conn drep False

-- | Submit a DRep certificate in a transaction that spends a faucet input and
-- has no outputs, witnessed by the faucet key and the DRep key. The fee
-- balances the faucet input against the deposit or the refund of the
-- certificate.
submitDRepCertificate
    :: CardanoNodeConn
    -> DRepKeyHash
    -> FileOf "drep-cert"
    -> Integer
    -- ^ Fee
    -> String
    -- ^ Name of the certificate, for files and logs
    -> ClusterM ()
submitDRepCertificate conn drep (FileOf cert) fee name = do
    Config{..} <- ask
    drepDir <- askDRepDir drep
    let txBody = drepDir </> relFile (name <> ".tx.raw")
    (faucetInput, faucetPrv) <- takeFaucet
    cli
        [ clusterEraToString cfgLastHardFork
        , "transaction"
        , "build-raw"
        , "--tx-in"
        , untag faucetInput
        , "--ttl"
        , "6000000"
        , "--fee"
        , show fee
        , "--certificate-file"
        , toFilePath cert
        , "--out-file"
        , toFilePath txBody
        ]
    signAndSubmitTx
        conn
        (FileOf txBody)
        [ changeFileOf faucetPrv
        , FileOf $ drepDir </> signingKeyFile
        ]
        (Tagged @"name" $ "DRep " <> name)

-- | The deposit of the DRep, if the ledger holds the DRep as registered.
queryDRepDeposit
    :: CardanoNodeConn -> DRepKeyHash -> ClusterM (Maybe Integer)
queryDRepDeposit conn drep = do
    states <-
        cliQuery
            conn
            [ "query"
            , "drep-state"
            , "--drep-key-hash"
            , drepKeyHashHex drep
            , "--output-json"
            ]
    case states ^? _Array of
        Just entries | null entries -> pure Nothing
        _ ->
            maybe (unexpected "DRep state" states) (pure . Just)
                $ states ^? nth 0 . nth 1 . key "deposit" . _Integer

-- | Wait until the ledger holds the DRep as registered, or as not registered.
waitForDRep :: CardanoNodeConn -> DRepKeyHash -> Bool -> ClusterM ()
waitForDRep conn drep expected = do
    registered <-
        retrying
            (limitRetriesByCumulativeDelay 120_000_000 $ constantDelay 1_000_000)
            (\_ registered -> pure $ registered /= expected)
            (\_ -> isJust <$> queryDRepDeposit conn drep)
    when (registered /= expected)
        $ liftIO
        $ throwIO
        $ userError
        $ unwords
            [ "DRep"
            , drepKeyHashHex drep
            , if expected then "is not registered" else "is still registered"
            , "after 120 seconds"
            ]

-- | Run a @cardano-cli@ ledger query against the node and decode its JSON
-- output.
cliQuery :: CardanoNodeConn -> [String] -> ClusterM Value
cliQuery conn args = do
    Config{..} <- ask
    process <-
        cliConfigNode conn
            $ [clusterEraToString cfgLastHardFork]
                <> args
                <> [ "--testnet-magic"
                   , show (testnetMagicToNatural cfgTestnetMagic)
                   ]
    (status, out, err) <- liftIO $ readProcess process
    case status of
        ExitSuccess ->
            either
                (\e -> liftIO $ throwIO $ userError $ unwords args <> ": " <> e)
                pure
                $ eitherDecode out
        ExitFailure _ ->
            liftIO
                $ throwIO
                $ userError
                $ unwords args <> " failed: " <> BL8.unpack err

unexpected :: String -> Value -> ClusterM a
unexpected what value =
    liftIO
        $ throwIO
        $ userError
        $ "Unexpected " <> what <> ": " <> show value

askDRepDir :: DRepKeyHash -> ClusterM AbsDir
askDRepDir drep = do
    DirOf clusterDir <- asks cfgClusterDir
    pure $ clusterDir </> relDir "dreps" </> relDir (drepKeyHashHex drep)

verificationKeyFile :: RelFile
verificationKeyFile = relFile "drep.vkey"

signingKeyFile :: RelFile
signingKeyFile = relFile "drep.skey"

drepKeyHashHex :: DRepKeyHash -> String
drepKeyHashHex = B8.unpack . convertToBase Base16 . getDRepKeyHash
